public class Sala {
    private int id;
    private String nombre;
    //--------------------CONSTRUCTORES--------------------
    public Sala(int id, String nombre) {
        this.nombre = nombre;
        this.id = id;
    }
    // --------------------LISTAS--------------------
    //--------------------METODOS--------------------
    //--------------------GETTERS--------------------

    public String getNombre() {
        return nombre;
    }
    public int getId() {
        return id;
    }
    //--------------------SETTERS-------------------
}



