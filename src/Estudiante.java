public class Estudiante {
    private String legajo;
    private String nombre;

    //--------------------CONSTRUCTORES--------------------
    public Estudiante(String legajo, String nombre) {
        this.legajo = legajo;
        this.nombre = nombre;
    }
    // --------------------LISTAS--------------------
    //--------------------METODOS--------------------
    //--------------------GETTERS--------------------
    public String getLegajo() {
        return legajo;
    }

    public String getNombre() {
        return nombre;
    }
    //--------------------SETTERS--------------------
}




